<?php
/**
 * IndexNow: generate the key and submit URLs.
 *
 *   php bin/indexnow.php --init            generate a key, write conf/indexnow.php + <key>.txt
 *   php bin/indexnow.php --status          show the key, whether it is publicly readable,
 *                                          and which URLs would be submitted
 *   php bin/indexnow.php --dry-run         print the exact JSON payload, send nothing
 *   php bin/indexnow.php                   submit every URL in sitemap.xml
 *   php bin/indexnow.php --url=/docs       submit one URL (resolved against seo.site)
 *
 * What a 200/202 means is printed with every result, because the difference between
 * "accepted for crawling" and "indexed" is the whole story of this protocol.
 *
 * Google is not a participant. Nothing here can submit to Google; that is the
 * sitemap plus a verified Search Console property (see OPERATIONS.md §5.10).
 */

use SatApi\Config;
use SatApi\Http\Client;
use SatApi\Support\IndexNow;
use SatApi\Support\Seo;

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit("CLI only\n");
}

require __DIR__ . '/../bootstrap.php';

$mode = 'submit';
$single = null;
foreach (array_slice($argv, 1) as $arg) {
    if ($arg === '--init') {
        $mode = 'init';
    } elseif ($arg === '--status') {
        $mode = 'status';
    } elseif ($arg === '--dry-run') {
        $mode = 'dry-run';
    } elseif (strpos($arg, '--url=') === 0) {
        $single = substr($arg, 6);
    } else {
        fwrite(STDERR, "unknown option: $arg\n");
        exit(2);
    }
}

/* ------------------------------------------------------------------ --init */

if ($mode === 'init') {
    $existing = IndexNow::key();
    if ($existing !== '') {
        echo "A key already exists: $existing\n";
        echo "Refusing to rotate it silently -- engines have it cached and the old key\n";
        echo "file would keep answering. Delete conf/indexnow.php and " . $existing . ".txt\n";
        echo "if a rotation is really intended.\n";
        exit(0);
    }

    $key = bin2hex(random_bytes(16));
    $conf = Config::path('conf/indexnow.php');
    $body = "<?php\n"
        . "/**\n"
        . " * IndexNow key. Generated by `php bin/indexnow.php --init`.\n"
        . " *\n"
        . " * NOT a secret: the protocol requires this exact string to be published at\n"
        . " * " . Seo::site() . '/' . $key . ".txt. It lives in a file so the key and the\n"
        . " * published verification file cannot disagree.\n"
        . " */\n\n"
        . "return array(\n"
        . "    'key' => '" . $key . "',\n"
        . ");\n";
    if (@file_put_contents($conf, $body) === false) {
        fwrite(STDERR, "cannot write $conf\n");
        exit(1);
    }
    @chmod($conf, 0640);

    $file = Config::path($key . '.txt');
    if (@file_put_contents($file, $key) === false) {
        fwrite(STDERR, "cannot write $file\n");
        exit(1);
    }
    // 0644: nginx serves static files as its worker user, and a root-owned 0600 key
    // file answers 403 to the very engine the protocol asks to read it.
    @chmod($file, 0644);

    echo "key         : $key\n";
    echo "conf        : $conf\n";
    echo "key file    : $file\n";
    echo "public URL  : " . Seo::site() . '/' . $key . ".txt\n";
    echo "\nNext: make sure that URL answers 200 with exactly the key, then:\n";
    echo "  php bin/indexnow.php --status\n";
    exit(0);
}

/* ----------------------------------------------------------------- status */

$key = IndexNow::key();
if ($key === '') {
    fwrite(STDERR, "no key yet: run `php bin/indexnow.php --init` first\n");
    exit(1);
}

$urls = IndexNow::urls();
echo "host        : " . IndexNow::host() . "\n";
echo "canonical   : " . Seo::site() . "\n";
echo "key         : $key\n";
echo "keyLocation : " . IndexNow::keyLocation() . "\n";
echo "key file    : " . IndexNow::keyFile() . " (" . (is_file(IndexNow::keyFile()) ? filesize(IndexNow::keyFile()) . " bytes" : "MISSING") . ")\n";

// The engines fetch this URL; check it the same way they will, over HTTPS.
$probe = Client::get(IndexNow::keyLocation(), array('timeout' => 15, 'retries' => 1));
$fetched = trim((string) $probe['body']);
printf(
    "public read : HTTP %d, body %s\n",
    (int) $probe['status'],
    $fetched === $key ? 'matches the key' : ('does NOT match (' . substr($fetched, 0, 40) . ')')
);
if ((int) $probe['status'] !== 200 || $fetched !== $key) {
    echo "              ^ the submission will be rejected with 403 until this is fixed\n";
}

echo "urls        : " . count($urls) . " from sitemap.xml\n";
foreach ($urls as $url) {
    echo "  - $url\n";
}

if ($mode === 'status') {
    exit((int) $probe['status'] === 200 && $fetched === $key ? 0 : 1);
}

/* ---------------------------------------------------------------- dry-run */

if ($mode === 'dry-run') {
    echo "\npayload for " . IndexNow::ENDPOINTS['indexnow'] . ":\n";
    echo json_encode(IndexNow::payload($urls), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n";
    exit(0);
}

/* ----------------------------------------------------------------- submit */

if ($single !== null) {
    $single = trim($single);
    $target = strpos($single, 'http') === 0 ? $single : Seo::site() . '/' . ltrim($single, '/');
    if (strpos($target, Seo::site() . '/') !== 0) {
        fwrite(STDERR, "$target does not belong to " . Seo::site() . " (422 from every engine)\n");
        exit(1);
    }
    $urls = array($target);
}

if (!$urls) {
    fwrite(STDERR, "nothing to submit: sitemap.xml listed no URL on " . Seo::site() . "\n");
    exit(1);
}

echo "\nsubmitting " . count($urls) . " URL(s)\n";
$results = IndexNow::submit($urls);
$failed = 0;
foreach ($results as $name => $result) {
    printf("  %-9s HTTP %-3d %s\n", $name, $result['status'], $result['verdict']);
    if ($result['body'] !== '') {
        echo "            body: " . trim($result['body']) . "\n";
    }
    if (!$result['ok']) {
        $failed++;
    }
}

echo "\n";
if ($failed === 0) {
    echo "Accepted for crawling by the participating engines (Bing, Yandex, Seznam, Naver).\n";
    echo "This is a queue for a CRAWL, not an indexing guarantee, and it does not reach\n";
    echo "Google -- Google has no IndexNow support; its channel is the sitemap plus a\n";
    echo "verified Search Console property.\n";
    exit(0);
}

echo "At least one endpoint rejected the submission. 403 means the key file is not\n";
echo "readable at keyLocation (run --status); 422 means a URL is not on this host.\n";
exit(1);
